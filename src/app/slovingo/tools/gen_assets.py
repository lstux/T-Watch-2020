#!/usr/bin/env python3
"""Generate the LVGL 7 assets of the Slovingo app (fonts and icon).

lv_font_conv is not needed: the font is written straight from a TTF with
Pillow (FreeType) in the plain lv_font_fmt_txt format (no kerning, no
compression). The default Ubuntu_* fonts of this firmware only cover
U+20..U+7E and U+A0..U+FF; Slovak also needs c-caron, d-caron, l-acute,
l-caron, n-caron, r-acute, s-caron, t-caron, z-caron..., so the fonts below
cover Basic Latin + Latin-1 + Latin Extended-A (U+20..U+17F).

Usage (from the repository root, needs Pillow and DejaVu Sans):
    python3 src/app/slovingo/tools/gen_assets.py

The fonts are derived from DejaVu Sans (free licence, see
https://dejavu-fonts.github.io/License.html).
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

APP_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
TTF_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

# (first code point, last code point), one FORMAT0_TINY cmap each
RANGES = [(0x20, 0x7E), (0xA0, 0x17F)]
BPP = 4
SIZES = (16, 22)


def glyph_bitmap(font, ch):
    """Return (bytes, box_w, box_h, ofs_x, ofs_y, adv_w) for one character."""
    adv_w = int(round(font.getlength(ch) * 16))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return b"", 0, 0, 0, 0, adv_w
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, fill=255, font=font, anchor="ls")
    levels = (1 << BPP) - 1
    bits = []
    for px in img.get_flattened_data():
        bits.append(round(px * levels / 255))
    # pack MSB first, rows are NOT byte aligned, pad at the end of the glyph
    out = bytearray()
    acc = nbits = 0
    for v in bits:
        acc = (acc << BPP) | v
        nbits += BPP
        while nbits >= 8:
            out.append((acc >> (nbits - 8)) & 0xFF)
            nbits -= 8
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out), w, h, x0, -y1, adv_w


def write_font(size):
    name = "slovingo_%dpx" % size
    font = ImageFont.truetype(TTF, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    bitmaps, descs = bytearray(), [(0, 0, 0, 0, 0, 0)]  # glyph id 0 is reserved
    cmaps, first_id = [], 1
    for lo, hi in RANGES:
        cmaps.append((lo, hi - lo + 1, first_id))
        for cp in range(lo, hi + 1):
            data, w, h, ox, oy, adv = glyph_bitmap(font, chr(cp))
            descs.append((len(bitmaps) if data else 0, adv, w, h, ox, oy))
            bitmaps += data
        first_id += hi - lo + 1

    guard = name.upper()
    lines = [
        "// Generated by tools/gen_assets.py from DejaVu Sans, do not edit.",
        '#include "lvgl.h"',
        "",
        "#ifndef %s" % guard, "#define %s 1" % guard, "#endif", "",
        "#if %s" % guard, "",
        "static LV_ATTRIBUTE_LARGE_CONST const uint8_t gylph_bitmap[] = {",
    ]
    for i in range(0, len(bitmaps), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmaps[i:i + 16]) + ",")
    if not bitmaps:
        lines.append("    0x00")
    lines += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"]
    for i, (bi, adv, w, h, ox, oy) in enumerate(descs):
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}%s"
                     % (bi, adv, w, h, ox, oy, ("," if i < len(descs) - 1 else "")))
    lines += ["};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {"]
    for i, (start, length, gid) in enumerate(cmaps):
        lines.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, .unicode_list = NULL,"
                     " .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}%s"
                     % (start, length, gid, ("," if i < len(cmaps) - 1 else "")))
    lines += [
        "};", "",
        "static lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = gylph_bitmap,", "    .glyph_dsc = glyph_dsc,", "    .cmaps = cmaps,",
        "    .kern_dsc = NULL,", "    .kern_scale = 0,", "    .cmap_num = %d," % len(cmaps),
        "    .bpp = %d," % BPP, "    .kern_classes = 0,", "    .bitmap_format = 0", "};", "",
        "lv_font_t %s = {" % name,
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        "    .line_height = %d," % (ascent + descent),
        "    .base_line = %d," % descent,
        "#if !(LVGL_VERSION_MAJOR == 6 && LVGL_VERSION_MINOR == 0)",
        "    .subpx = LV_FONT_SUBPX_NONE,",
        "#endif",
        "    .dsc = &font_dsc",
        "};", "", "#endif /* %s */" % guard, "",
    ]
    path = os.path.join(APP_DIR, "font", name + ".c")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("%s: %d glyphs, %d bitmap bytes" % (path, len(descs) - 1, len(bitmaps)))


def draw_icon(size):
    big = size * 8
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((big * 0.04, big * 0.04, big * 0.96, big * 0.96), radius=big * 0.22, fill=(11, 78, 162, 255))
    # Slovak flag stripes along the bottom, under a white speech bubble
    d.rounded_rectangle((big * 0.16, big * 0.14, big * 0.84, big * 0.66), radius=big * 0.14, fill=(255, 255, 255, 255))
    d.polygon([(big * 0.30, big * 0.62), (big * 0.30, big * 0.82), (big * 0.52, big * 0.62)], fill=(255, 255, 255, 255))
    font = ImageFont.truetype(TTF_BOLD, int(big * 0.42))
    d.text((big * 0.50, big * 0.40), "S", fill=(11, 78, 162, 255), font=font, anchor="mm")
    d.rectangle((big * 0.62, big * 0.74, big * 0.88, big * 0.78), fill=(238, 28, 37, 255))
    return img.resize((size, size), Image.LANCZOS)


def write_icon(size):
    name = "slovingo_%dpx" % size
    img = draw_icon(size)
    px = list(img.get_flattened_data())

    def fmt8(r, g, b, a):
        return [(r >> 5) << 5 | (g >> 5) << 2 | (b >> 6), a]

    def fmt16(r, g, b, a, swap=False):
        v = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
        lo, hi = v & 0xFF, v >> 8
        return ([hi, lo] if swap else [lo, hi]) + [a]

    variants = [
        ("LV_COLOR_DEPTH == 1 || LV_COLOR_DEPTH == 8", "Blue: 2 bit, Green: 3 bit, Red: 3 bit, Alpha 8 bit", fmt8),
        ("LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 0", "Blue: 5 bit, Green: 6 bit, Red: 5 bit, Alpha 8 bit", fmt16),
        ("LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP != 0", "same, the 2 colour bytes swapped", lambda *p: fmt16(*p, swap=True)),
        ("LV_COLOR_DEPTH == 32", "Blue, Green, Red, Alpha", lambda r, g, b, a: [b, g, r, a]),
    ]
    out = [
        "// Generated by tools/gen_assets.py, do not edit.",
        "#if defined(LV_LVGL_H_INCLUDE_SIMPLE)", '#include "lvgl.h"', "#else", '#include "../lvgl/lvgl.h"', "#endif", "",
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN", "#define LV_ATTRIBUTE_MEM_ALIGN", "#endif", "",
        "#ifndef LV_ATTRIBUTE_IMG_%s" % name.upper(), "#define LV_ATTRIBUTE_IMG_%s" % name.upper(), "#endif", "",
        "const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_IMG_%s uint8_t %s_map[] = {" % (name.upper(), name),
    ]
    for cond, comment, fn in variants:
        out += ["#if " + cond, "  /*Pixel format: %s*/" % comment]
        data = [b for p in px for b in fn(*p)]
        for i in range(0, len(data), 20):
            out.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
        out.append("#endif")
    out += [
        "};", "",
        "const lv_img_dsc_t %s = {" % name,
        "  .header.always_zero = 0,", "  .header.w = %d," % size, "  .header.h = %d," % size,
        "  .data_size = %d * LV_IMG_PX_SIZE_ALPHA_BYTE," % (size * size),
        "  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,", "  .data = %s_map," % name, "};", "",
    ]
    path = os.path.join(APP_DIR, "images", name + ".c")
    with open(path, "w") as f:
        f.write("\n".join(out))
    img.save(os.path.join(APP_DIR, "tools", name + "_preview.png"))
    print(path)


if __name__ == "__main__":
    if not os.path.exists(TTF):
        sys.exit("DejaVu Sans not found at " + TTF)
    for s in SIZES:
        write_font(s)
    write_icon(64)
